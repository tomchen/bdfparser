def _corrupt_cases():
    good = ours('syn-proportional')
    toc = parse_toc(good)
    met_fmt, _s, met_off = toc[4]
    bmp_fmt, _s, bmp_off = toc[8]
    enc_off = toc[32][2]
    cases = {
        'empty': b'',
        'bad magic': b'\x01fcq' + good[4:],
        'truncated toc': good[:20],
        'huge table count': good[:4] + struct.pack('<I', 100000) + good[8:],
        'no metrics': strip_tables(good, {4}),
        'no bitmaps': strip_tables(good, {8}),
        'metrics past end': set_toc_entry(good, 4, offset=len(good) + 10),
        'bad metrics format': good[:met_off]
        + struct.pack('<I', 0x200 | met_fmt)
        + good[met_off + 4 :],
        'truncated': good[: bmp_off + 40],
    }
    # bitmap count mismatch
    b = bytearray(good)
    struct.pack_into('>I', b, bmp_off + 4, 3)
    cases['bitmap count'] = bytes(b)
    # bitmap offset beyond the data
    b = bytearray(good)
    struct.pack_into('>I', b, bmp_off + 8, 0x7FFFFF)
    cases['bitmap offset'] = bytes(b)
    # encoding pointing to a missing glyph
    b = bytearray(good)
    struct.pack_into('>H', b, enc_off + 14, 500)
    cases['encoding index'] = bytes(b)
    # negative sized glyph (compressed metrics: rsb < lsb)
    b = bytearray(good)
    if met_fmt & 0x100:
        b[met_off + 6] = 0x90
        b[met_off + 7] = 0x80
    else:
        struct.pack_into('>2h', b, met_off + 8, 10, 0)
    cases['negative glyph'] = bytes(b)
    # property string offset out of range
    b = bytearray(good)
    prop_off = toc[1][2]
    struct.pack_into('>I', b, prop_off + 8, 0x7FFFFFF)
    cases['property name offset'] = bytes(b)
    # swidth / glyph name count mismatch
    for t in (64, 128):
        b = bytearray(good)
        struct.pack_into('>I', b, toc[t][2] + 4, 1)
        cases[f'count mismatch {t}'] = bytes(b)
    return cases


