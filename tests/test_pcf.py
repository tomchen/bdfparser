def test_golden_files_present():
    sums = read_sums()
    expected = [(n, ()) for n in ALL_FONTS + sorted(SYNTHETIC)]
    expected += [(n, f) for n in FLAG_FONTS for f in FLAG_SETS]
    missing = [golden_name(n, f) for n, f in expected if golden_name(n, f) not in sums]
    assert not missing, f'golden checksums missing: {missing[:5]}'
    for n, f in expected:
        assert (GOLDEN / (golden_name(n, f) + '.gz')).exists() == golden_file_stored(n, f)
    names = [p.name.lower() for p in GOLDEN.iterdir()]
    assert len(names) == len(set(names))
