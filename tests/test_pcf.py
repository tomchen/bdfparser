def quiet_font(source) -> Font:
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        if isinstance(source, Path):
            return Font(str(source))
        return Font().load_string(source)


@functools.cache
def load(name: str) -> Font:
    """A test font by file name, or a synthetic font by its SYNTHETIC key."""
    if name in SYNTHETIC:
        return quiet_font(SYNTHETIC[name])
    return quiet_font(FONTS / name)


@functools.cache
def ours(name: str, flags: tuple[str, ...] = ()) -> bytes:
    return write_pcf(load(name), **flags_to_options(flags))


def run_bdftopcf(bdf: bytes, flags: tuple[str, ...] = ()) -> bytes:
    assert BDFTOPCF is not None
    res = subprocess.run([BDFTOPCF, *flags], input=bdf, capture_output=True, check=False)
    if res.returncode != 0:
        raise RuntimeError(f'bdftopcf failed: {res.stderr.decode(errors="replace")}')
    return res.stdout


def _glyph_entries(font: Font):
    for cp, meta in font.glyphs.items():
        yield meta, cp, None
    for entry in font.unencoded:
        yield entry['meta'], -1, entry['altcode']


def _token(name) -> str:
    parts = str(name or '').encode('utf-8').split()
    return parts[0][:99].decode('utf-8', 'replace') if parts else ''


def bdf_for_bdftopcf(font: Font) -> bytes:
    """
    Canonical BDF accepted by bdftopcf, spelling out write_pcf's interpretation
    of the model (fallbacks, skipped properties, row padding, name tokens).
    """
    h = font.headers
    xres = h.get('xres') or 75
    yres = h.get('yres') or 75
    xres = xres if xres >= 1 else 75
    yres = yres if yres >= 1 else 75
    lines = [
        'STARTFONT 2.1',
        f'FONT {h.get("fontname") or ""}',
        f'SIZE {h.get("pointsize") or 0} {xres} {yres}',
        f'FONTBOUNDINGBOX {h["fbbx"]} {h["fbby"]} {h["fbbxoff"]} {h["fbbyoff"]}',
    ]
    props = []
    have_asc = have_desc = False
    for key, value in font.props.items():
        if key == 'comment' or value is None:
            continue
        name = font._propnames.get(key, key.upper())
        if name.startswith('COMMENT'):
            continue
        if isinstance(value, int):
            props.append(f'{name} {int(value)}')
            have_asc = have_asc or name == 'FONT_ASCENT'
            have_desc = have_desc or name == 'FONT_DESCENT'
        elif name not in ('FONT_ASCENT', 'FONT_DESCENT', 'DEFAULT_CHAR'):
            props.append(f'{name} "' + str(value).replace('"', '""') + '"')
    if not have_asc:
        props.append(f'FONT_ASCENT {h["fbby"] + h["fbbyoff"]}')
    if not have_desc:
        props.append(f'FONT_DESCENT {-h["fbbyoff"]}')
    lines.append(f'STARTPROPERTIES {len(props)}')
    lines += props
    lines.append('ENDPROPERTIES')
    entries = list(_glyph_entries(font))
    lines.append(f'CHARS {len(entries)}')
    for meta, cp, alt in entries:
        bw, bh, bl, bb = (meta[2] or 0), (meta[3] or 0), (meta[4] or 0), (meta[5] or 0)
        dw = meta[8]
        if dw is None:
            dw = h.get('dwx0') if h.get('dwx0') is not None else max(0, bl + bw)
        sw = meta[6]
        if sw is None:
            sw = h.get('swx0') if h.get('swx0') is not None else font.swidth(dw)
        lines.append(f'STARTCHAR {_token(meta[0])}')
        lines.append(f'ENCODING {cp}' if alt is None else f'ENCODING -1 {alt}')
        lines.append(f'SWIDTH {sw} 0')
        lines.append(f'DWIDTH {dw} 0')
        lines.append(f'BBX {bw} {bh} {bl} {bb}')
        lines.append('BITMAP')
        hb = (bw + 7) // 8
        rows = list(meta[16] or [])
        if bw > 0:
            for r in range(bh):
                row = rows[r].strip() if r < len(rows) else ''
                lines.append(row or '00' * hb)
        lines.append('ENDCHAR')
    lines.append('ENDFONT')
    return ('\n'.join(lines) + '\n').encode('utf-8')


def reference(name: str, flags: tuple[str, ...] = ()) -> bytes:
    """bdftopcf output that write_pcf(load(name)) must reproduce."""
    if name in SYNTHETIC:
        return run_bdftopcf(SYNTHETIC[name].encode(), flags)
    if name in RAW_OK:
        return run_bdftopcf((FONTS / name).read_bytes(), flags)
    return run_bdftopcf(bdf_for_bdftopcf(load(name)), flags)


def golden_name(name: str, flags: tuple[str, ...] = ()) -> str:
    stem = name[:-4] if name.endswith('.bdf') else name
    return stem + ('.' + flags_slug(flags) if flags else '') + '.pcf'


def read_sums() -> dict[str, str]:
    sums = {}
    if SHA256SUMS.exists():
        for line in SHA256SUMS.read_text().splitlines():
            if line.strip():
                digest, fname = line.split(None, 1)
                sums[fname.strip()] = digest
    return sums


def write_golden(name: str, flags: tuple[str, ...], data: bytes) -> None:
    GOLDEN.mkdir(parents=True, exist_ok=True)
    gname = golden_name(name, flags)
    if golden_file_stored(name, flags):
        (GOLDEN / (gname + '.gz')).write_bytes(gzip.compress(data, mtime=0))
    sums = read_sums()
    sums[gname] = hashlib.sha256(data).hexdigest()
    SHA256SUMS.write_text(''.join(f'{sums[k]}  {k}\n' for k in sorted(sums)))


# fonts of FLAG_FONTS that get ink metrics (constant metrics) or terminal padding
INK_OR_PADDED = {'unifont-13.0.04-2atest.bdf', 'syn-terminal'}


def bdftopcf_swap_bug(name: str, flags: tuple[str, ...]) -> bool:
    """
    bdftopcf byte-swaps (bit order != byte order, scan unit > 1) before terminal
    padding and ink metrics, garbling both; write_pcf swaps last (see pcf.py).
    """
    o = flags_to_options(flags)
    swapped = o.get('bitorder', 'msb') != o.get('byteorder', 'msb') and o.get('scanunit', 1) > 1
    return swapped and name in INK_OR_PADDED


def table_bytes(data: bytes) -> dict[int, bytes]:
    return {t: data[o : o + s] for t, (_f, s, o) in parse_toc(data).items()}


def check_against_reference(name: str, flags: tuple[str, ...] = ()) -> None:
    got = ours(name, flags)
    gname = golden_name(name, flags)
    if BDFTOPCF is not None:
        expected = reference(name, flags)
        if bdftopcf_swap_bug(name, flags):
            # only the tables bdftopcf computes from the swapped buffer may differ
            a, b = table_bytes(got), table_bytes(expected)
            assert a.keys() == b.keys()
            for t in a:
                if t not in (1, 2, 8, 16, 256):
                    assert a[t] == b[t], t
            assert len(got) == len(expected)
            expected = got
        if REGEN:
            write_golden(name, flags, expected)
        assert_same_pcf(got, expected)
    digest = read_sums().get(gname)
    assert digest is not None, f'golden checksum for {gname} missing (regenerate)'
    gz = GOLDEN / (gname + '.gz')
    if gz.exists():
        assert_same_pcf(got, gzip.decompress(gz.read_bytes()))
        assert model_of(read_pcf(gz.read_bytes())) == model_of(read_pcf(got))
    assert hashlib.sha256(got).hexdigest() == digest


def assert_same_pcf(got: bytes, expected: bytes) -> None:
    if got == expected:
        return
    n = next((i for i, (a, b) in enumerate(zip(got, expected, strict=False)) if a != b), None)
    pytest.fail(
        f'PCF differs: len {len(got)} vs {len(expected)}, first difference at byte {n}'
        f' ({toc_location(expected, n)})'
    )


def toc_location(data: bytes, pos: int | None) -> str:
    if pos is None or len(data) < 8:
        return 'length only'
    n = struct.unpack_from('<I', data, 4)[0]
    for i in range(n):
        t, _f, s, o = struct.unpack_from('<4I', data, 8 + 16 * i)
        if o <= pos < o + s:
            return f'table type {t}, offset {pos - o}'
    return 'table of contents'


def ink_pixels(meta) -> set[tuple[int, int]]:
    """Ink pixels relative to the glyph origin (x right, y up)."""
    bw, bh, bl, bb = meta[2], meta[3], meta[4], meta[5]
    out = set()
    rows = meta[16] or []
    for r in range(min(bh, len(rows))):
        row = rows[r].strip()
        if not row or bw == 0:
            continue
        bits = bin(int(row, 16))[2:].zfill(len(row) * 4)[:bw]
        for c, b in enumerate(bits):
            if b == '1':
                out.add((bl + c, bb + bh - 1 - r))
    return out


def model_of(font: Font):
    """Comparable snapshot of a font (headers, props, glyphs, unencoded)."""
    return (
        dict(font.headers),
        dict(font.props),
        {cp: list(m) for cp, m in font.glyphs.items()},
        [(e['altcode'], list(e['meta'])) for e in font.unencoded],
    )


def expected_placement(font: Font):
    """-> (encoded {cp: meta}, unencoded [meta]) as bdftopcf/read_pcf place them."""
    enc: dict[int, list] = {}
    unenc: list[list] = []
    for meta, cp, alt in _glyph_entries(font):
        code = alt if alt is not None and alt >= 0 else cp
        if 0 <= code <= 0xFFFF:
            if code in enc:  # a later glyph takes over the code
                unenc.append(enc.pop(code))
            enc[code] = meta
        else:
            unenc.append(meta)
    return enc, unenc


def assert_roundtrip(orig: Font, back: Font) -> None:
    """read_pcf(write_pcf(orig)) must reproduce orig (modulo documented changes)."""
    h = orig.headers
    enc, unenc = expected_placement(orig)
    assert sorted(back.glyphs) == sorted(enc)
    pairs = [(enc[cp], back.glyphs[cp]) for cp in enc]
    # unencoded glyphs keep their relative (glyph index) order
    order = {id(m): i for i, (m, _cp, _alt) in enumerate(_glyph_entries(orig))}
    unenc.sort(key=lambda m: order[id(m)])
    assert len(back.unencoded) == len(unenc)
    pairs += [(m, e['meta']) for m, e in zip(unenc, back.unencoded, strict=True)]
    for e in back.unencoded:
        assert e['altcode'] is None and e['meta'][1] == -1
    # terminal padding: all glyphs got the same box
    boxes = {tuple(b[2:6]) for _o, b in pairs}
    padded = any(tuple(o[2:6]) != tuple(b[2:6]) for o, b in pairs)
    if padded:
        assert len(boxes) == 1
    for o, b in pairs:
        dw = o[8] if o[8] is not None else h.get('dwx0', max(0, o[4] + o[2]))
        sw = (
            o[6]
            if o[6] is not None
            else (h.get('swx0') if h.get('swx0') is not None else orig.swidth(dw))
        )
        assert b[0] == _token(o[0])
        assert b[6:10] == [sw, 0, (b[2] if padded else dw), 0]
        assert b[10:16] == [None] * 6
        assert len(b[16]) == (b[3] if b[2] else 0)
        assert all(len(row) == (b[2] + 7) // 8 * 2 for row in b[16])
        if padded:
            bw, bh, bl, bb = b[2:6]
            clip = {(x, y) for x, y in ink_pixels(o) if bl <= x < bl + bw and bb <= y < bb + bh}
            assert ink_pixels(b) == clip
        else:
            assert b[2:6] == o[2:6]
            assert ink_pixels(b) == ink_pixels(o)
    # properties
    for key, value in orig.props.items():
        if key == 'comment' or value is None:
            continue
        name = orig._propnames.get(key, key.upper())
        if name.startswith('COMMENT'):
            continue
        if name in ('FONT_ASCENT', 'FONT_DESCENT') and not isinstance(value, int):
            continue
        if name == 'DEFAULT_CHAR':
            if isinstance(value, int) and value & 0xFFFF not in (0, 0xFFFF):
                assert back.props['default_char'] == value & 0xFFFF
            continue
        if name == 'FONT' and isinstance(value, str):
            assert back.headers['fontname'] == value  # and kept in props (below)
        if name in ('X_HEIGHT', 'WEIGHT', 'QUAD_WIDTH') and value == -1:
            continue  # recomputed by bdftopcf
        assert back.props[key] == value, key
        assert back._propnames[key] == name
    extra = set(back.props) - set(orig.props) - {'font_ascent', 'font_descent', 'default_char'}
    assert extra <= GENERATED_PROPS
    if isinstance(orig.props.get('font_ascent'), int):
        assert back.props['font_ascent'] == orig.props['font_ascent']
    else:
        assert back.props['font_ascent'] == h['fbby'] + h['fbbyoff']
    # headers
    assert back.headers['bdfversion'] == 2.1
    assert back.headers['metricsset'] == 0
    if 'font' not in orig.props:
        assert back.headers['fontname'] == (h.get('fontname') or '')
    assert back.headers['xres'] == (orig.props.get('resolution_x') or h['xres'])
    assert back.headers['yres'] == (orig.props.get('resolution_y') or h['yres'])
    assert back.headers['pointsize'] == math.floor(back.props['point_size'] / 10 + 0.5)
    assert list(back.headers)[:5] == ['bdfversion', 'fontname', 'pointsize', 'xres', 'yres']


