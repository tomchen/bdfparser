# seeded random fonts (property tests)


def random_font(seed: int) -> Font:
    rnd = random.Random(seed)
    mono = rnd.random() < 0.35
    asc = rnd.randint(4, 14)
    desc = rnd.randint(0, 4)
    cell = rnd.randint(3, 12)
    font = bare_font(
        fontname=f'random-{seed}',
        pointsize=rnd.choice([8, 10, 12, 16]),
        xres=rnd.choice([75, 100]),
        yres=rnd.choice([75, 100]),
        fbbx=cell,
        fbby=asc + desc,
        fbbxoff=0,
        fbbyoff=-desc,
    )
    if rnd.random() < 0.8:
        font.setprop('FONT_ASCENT', asc)
        font.setprop('FONT_DESCENT', desc)
    if rnd.random() < 0.5:
        font.setprop('DEFAULT_CHAR', rnd.randint(0, 0x2FF))
    for i in range(rnd.randint(0, 4)):
        font.setprop(f'PROP_{i}', rnd.choice([rnd.randint(-(2**31), 2**31 - 1), f'value {i} "q"']))
    if rnd.random() < 0.3:
        font.setprop('X_HEIGHT', -1)
    names = ['x', '0', '1', '5', 'a b', 'glyph']
    cps = rnd.sample(range(0, 0x500), rnd.randint(1, 25))
    if rnd.random() < 0.3:
        cps.append(rnd.randint(0x10000, 0x10FFFF))
    entries = []
    for cp in cps:
        if mono:
            bw = rnd.randint(0, cell)
            bl = rnd.randint(0, cell - bw)
            bh = rnd.randint(0, asc + desc)
            bb = rnd.randint(-desc, asc - bh)
            dw = cell
        else:
            bw = rnd.randint(0, 20)
            bh = rnd.randint(0, 20)
            bl = rnd.randint(-5, 5)
            bb = rnd.randint(-6, 6)
            dw = rnd.randint(-3, 24)
        hb = (bw + 7) // 8
        rows = []
        for _ in range(bh):
            v = rnd.getrandbits(hb * 8) if hb else 0
            if rnd.random() < 0.7 and bw % 8:
                v &= ~((1 << (8 - bw % 8)) - 1)  # clean bits beyond width
            rows.append(f'{v:0{hb * 2}X}' if hb else '')
        if bw == 0:
            rows = [''] * bh
        name = rnd.choice(names) + ('' if rnd.random() < 0.5 else str(cp))
        sw = font.swidth(dw) if rnd.random() < 0.8 else None
        entries.append((cp, meta(name, cp, [bw, bh, bl, bb], rows, dw=dw, sw=sw)))
    nun = rnd.randint(0, 3)
    for cp, m in entries[: len(entries) - nun]:
        font.glyphs[cp] = m
    for _cp, m in entries[len(entries) - nun :]:
        m[1] = -1
        alt = rnd.choice([None, None, rnd.randint(0, 0x500)])
        font.unencoded.append({'altcode': alt, 'meta': m})
    return font


RANDOM_SEEDS = list(range(60))


@pytest.mark.parametrize('seed', RANDOM_SEEDS)
def test_random_fonts(seed):
    font = random_font(seed)
    data = write_pcf(font)
    back = read_pcf(data)
    assert_roundtrip(font, back)
    assert write_pcf(read_pcf(write_pcf(back))) == write_pcf(back)
    rnd = random.Random(seed)
    opts = rnd.choice(OPTION_COMBOS)
    assert model_of(read_pcf(write_pcf(font, **opts))) == model_of(back)
    if BDFTOPCF is not None:
        assert_same_pcf(data, run_bdftopcf(bdf_for_bdftopcf(font)))
        flags = rnd.choice(FLAG_SETS)
        got = write_pcf(font, **flags_to_options(flags))
        expected = run_bdftopcf(bdf_for_bdftopcf(font), flags)
        o = flags_to_options(flags)
        if o.get('bitorder', 'msb') != o.get('byteorder', 'msb') and o.get('scanunit', 1) > 1:
            # bdftopcf swap bug (see pcf.py): bitmap / ink tables may differ
            a, b = table_bytes(got), table_bytes(expected)
            assert {t: v for t, v in a.items() if t not in (1, 2, 8, 16, 256)} == {
                t: v for t, v in b.items() if t not in (1, 2, 8, 16, 256)
            }
            if 16 not in a:  # no ink metrics => no padding either: identical
                assert_same_pcf(got, expected)
        else:
            assert_same_pcf(got, expected)


