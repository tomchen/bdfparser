def flags_to_options(flags: tuple[str, ...]) -> dict:
    opts: dict = {}
    for f in flags:
        if f.startswith('-p'):
            opts['glyphpad'] = int(f[2])
        elif f.startswith('-u'):
            opts['scanunit'] = int(f[2])
        elif f == '-l':
            opts['bitorder'] = 'lsb'
        elif f == '-m':
            opts['bitorder'] = 'msb'
        elif f == '-L':
            opts['byteorder'] = 'lsb'
        elif f == '-M':
            opts['byteorder'] = 'msb'
    return opts


_SLUG = {'-l': 'lsbbit', '-m': 'msbbit', '-L': 'lsbbyte', '-M': 'msbbyte'}


def flags_slug(flags: tuple[str, ...]) -> str:
    # case-insensitive file systems: -l / -L must not differ only by case
    return '-'.join(_SLUG.get(f, f.lstrip('-')) for f in flags)


