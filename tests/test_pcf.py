# fonts whose glyph list interleaves glyphs that end up unencoded (cp > 0xFFFF
# in syn-terminal) with encoded ones: read_pcf puts them in `unencoded`,
# written after the encoded glyphs, so only a one-cycle fixpoint holds
INTERLEAVED = {'syn-terminal'}


def assert_pcf_model_pcf(p0: bytes, **opts) -> None:
    """write_pcf(read_pcf(p0)) == p0, or a one-cycle fixpoint for INTERLEAVED fonts."""
    m0 = read_pcf(p0)
    p1 = write_pcf(m0, **opts)
    interleaved = {load(n).headers['fontname'] for n in INTERLEAVED}
    if m0.headers['fontname'] not in interleaved:
        assert_same_pcf(p1, p0)
    else:
        assert p1 != p0
        assert write_pcf(read_pcf(p1), **opts) == p1
        assert model_of(read_pcf(p1)) == model_of(m0)


def options_from_format(fmt: int) -> dict:
    return {
        'glyphpad': 1 << (fmt & 3),
        'scanunit': 1 << ((fmt >> 4) & 3),
        'byteorder': 'msb' if fmt & 4 else 'lsb',
        'bitorder': 'msb' if fmt & 8 else 'lsb',
    }


