def parse_toc(data: bytes) -> dict[int, tuple[int, int, int]]:
    n = struct.unpack_from('<I', data, 4)[0]
    out = {}
    for i in range(n):
        t, f, s, o = struct.unpack_from('<4I', data, 8 + 16 * i)
        out[t] = (f, s, o)
    return out


def strip_tables(data: bytes, drop: set[int]) -> bytes:
    """Remove tables from the TOC (their data stays where it is)."""
    n = struct.unpack_from('<I', data, 4)[0]
    keep = [data[8 + 16 * i : 24 + 16 * i] for i in range(n)]
    keep = [e for e in keep if struct.unpack_from('<I', e)[0] not in drop]
    header = b'\x01fcp' + struct.pack('<I', len(keep)) + b''.join(keep)
    return header + data[len(header) :]


def set_toc_entry(data: bytes, ttype: int, *, fmt=None, size=None, offset=None) -> bytes:
    buf = bytearray(data)
    n = struct.unpack_from('<I', buf, 4)[0]
    for i in range(n):
        t, f, s, o = struct.unpack_from('<4I', buf, 8 + 16 * i)
        if t == ttype:
            f = f if fmt is None else fmt
            struct.pack_into(
                '<4I',
                buf,
                8 + 16 * i,
                t,
                f,
                s if size is None else size,
                o if offset is None else offset,
            )
    return bytes(buf)


