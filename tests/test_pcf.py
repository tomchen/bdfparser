def bare_font(**headers) -> Font:
    font = Font()
    font.headers.update(
        {
            'bdfversion': 2.1,
            'fontname': 'bare',
            'pointsize': 10,
            'xres': 75,
            'yres': 75,
            'fbbx': 8,
            'fbby': 10,
            'fbbxoff': 0,
            'fbbyoff': -2,
            'metricsset': 0,
        }
    )
    font.headers.update(headers)
    return font


def meta(name, cp, bbx, rows, dw=None, sw=None):
    m = [None] * 17
    m[0], m[1] = name, cp
    m[2:6] = bbx
    m[6], m[7] = (sw, 0) if sw is not None else (None, None)
    m[8], m[9] = (dw, 0) if dw is not None else (None, None)
    m[16] = rows
    return m


def test_writer_fallbacks_and_odd_hex():
    font = bare_font(dwx0=7, swx0=None)
    font.setprop('COMMENTARY', 'skipped')
    font.setprop('KeyOnly', None)
    font.setprop('RawToken', 'abc')
    font.setprop('FONT_ASCENT', 'not an int')
    font.setprop('PIXEL_SIZE', True)
    font.props['comment'] = ['ignored']
    font.glyphs[65] = meta('A  name', 65, [12, 4, 0, 0], ['fff', 'ZZ12', '1', 'abcdef01'])
    font.glyphs[66] = meta('B', 66, [9, 3, 1, 0], ['FF80'])  # missing rows
    font.glyphs[67] = meta('x', 67, [3, 2, 0, -3], ['E0', 'A0'], dw=4)  # x below baseline
    font.glyphs[48] = meta('0', 48, [3, 2, 0, 0], ['E0', 'A0'], dw=5)
    font.glyphs[49] = meta('1', 49, [3, 2, 0, 0], ['E0', 'A0'], dw=8)
    font.unencoded.append({'altcode': None, 'meta': meta('', -1, [0, 0, 0, 0], [])})
    data = write_pcf(font)
    back = read_pcf(data)
    assert back.glyphs[65][0] == 'A'
    # 'ZZ' contributes nothing (bdfHexByte), 'fff' gets a '0' appended, bits
    # beyond the 12 px width are cleared, short rows are zero-padded
    assert back.glyphs[65][16] == ['FFF0', '0010', '1000', 'ABC0']
    assert back.glyphs[66][16] == ['FF80', '0000', '0000']
    assert back.glyphs[65][8] == 7  # headers dwx0
    assert back.glyphs[65][6] == round(7 * 72000 / (10 * 75))
    assert back.props['font_ascent'] == 8  # fbby + fbbyoff
    assert back.props['rawtoken'] == 'abc'
    assert back.props['pixel_size'] == 1
    assert 'commentary' not in back.props and 'keyonly' not in back.props
    assert back.props['x_height'] == 2  # bbh, since bbh + bbyoff <= 0
    assert back.props['quad_width'] == 6  # (5 + 8) // 2
    assert back.unencoded[0]['meta'][0] == ''  # bdftopcf would reject the empty name
    if BDFTOPCF is not None:
        font.unencoded[0]['meta'][0] = 'named'
        assert run_bdftopcf(bdf_for_bdftopcf(font)) == write_pcf(font)


def test_writer_without_dwidth_header():
    font = bare_font(pointsize=0)
    font.glyphs[65] = meta('A', 65, [3, 2, 2, 0], ['E0', 'A0'])
    back = read_pcf(write_pcf(font))
    assert back.glyphs[65][8] == 5  # max(0, bbxoff + bbw)
    assert back.glyphs[65][6] == round(5 * 1000 / 8)  # pointsize 0 => fbbx based


def test_writer_global_swidth_and_bad_resolution():
    font = bare_font(swx0=333, xres=0, yres=-1)
    font.glyphs[65] = meta('A', 65, [3, 2, 0, 0], ['E0', 'A0'], dw=4)
    back = read_pcf(write_pcf(font))
    assert back.glyphs[65][6] == 333
    assert back.props['resolution_x'] == 75 and back.props['resolution'] == 103


def test_writer_errors():
    font = bare_font()
    font.glyphs[65] = meta('A', 65, [-1, 2, 0, 0], [])
    with pytest.raises(PCFError, match='negative'):
        write_pcf(font)
    font.glyphs[65] = meta('A', 65, [2, 2, 40000, 0], ['C0', 'C0'], dw=1)
    with pytest.raises(PCFError, match='16 bits'):
        write_pcf(font)
    font.glyphs[65] = ['A', 65]
    with pytest.raises(PCFError, match='17-slot'):
        write_pcf(font)


def test_empty_font():
    font = bare_font()
    data = write_pcf(font)
    back = read_pcf(data)
    assert back.glyphs == {} and back.unencoded == []
    assert [back.headers[k] for k in ('fbbx', 'fbby', 'fbbxoff', 'fbbyoff')] == [0, 0, 0, 0]


def test_duplicate_code_from_altcode():
    font = bare_font()
    font.glyphs[65] = meta('A', 65, [3, 2, 0, 0], ['E0', 'A0'], dw=4)
    font.unencoded.append({'altcode': 65, 'meta': meta('A2', -1, [3, 2, 0, 0], ['40', '40'], dw=4)})
    back = read_pcf(write_pcf(font))
    assert back.glyphs[65][0] == 'A2'
    assert back.unencoded[0]['meta'][0] == 'A'
    assert_roundtrip(font, back)


def test_bare_meta_list_in_unencoded():
    font = bare_font()
    font.unencoded.append(meta('u', -1, [3, 2, 0, 0], ['E0', 'A0'], dw=4))
    back = read_pcf(write_pcf(font))
    assert back.unencoded[0]['meta'][0] == 'u'


